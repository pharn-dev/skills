#!/usr/bin/env node
// Regenerates the pharn-ci output embedded in the eval scaffolds, and the whole-file
// "unchanged" graders, from the real pharn-ci CLI and renderer. manifest.json pins one
// pharn-ci commit per version line, and each case names the version it was generated with.
// Node core only.
//
//   node plugins/pharn-ci/evals/fixtures/regen.mjs --check --pharn-ci 0.1.0=<checkout> --pharn-ci 0.2.0=<checkout>
//   node plugins/pharn-ci/evals/fixtures/regen.mjs --write --pharn-ci 0.1.0=<checkout> --pharn-ci 0.2.0=<checkout>
//
// Pass one checkout per version in manifest.pharnCi, each at its pinned commit and built first:
// pnpm install --frozen-lockfile && pnpm --filter @pharn-ci/cli... build
// --check exits 1 and prints a diff when a scaffold or grader is out of date; --write rewrites them.
import { spawnSync } from "node:child_process";
import { existsSync, mkdtempSync, readdirSync, readFileSync, realpathSync, rmSync, unlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const FIXTURES = path.dirname(fileURLToPath(import.meta.url));
const EVALS = path.dirname(FIXTURES);
const PLUGIN = path.dirname(EVALS);
const HELPER = path.join(PLUGIN, "skills/pharn-ci-install/scripts/check-coverage.mjs");
const PIN_REFERENCE = path.join(PLUGIN, "skills/pharn-ci-install/references/workflows.md");

export class RegenError extends Error {}

// ---------------------------------------------------------------- graders

/**
 * A JS RegExp source (no flags) that matches exactly `content` and nothing else: `^` and `$`
 * without the m flag anchor the whole text. Everything outside printable ASCII becomes a
 * \n, \t or \uHHHH escape, so the pattern stays on one line.
 */
export function wholeFilePattern(content) {
  if (!content.endsWith("\n")) throw new RegenError("a whole-file grader needs content that ends with a newline");
  let out = "^";
  for (const ch of content.slice(0, -1)) {
    if ("\\^$.*+?()[]{}|/".includes(ch)) out += `\\${ch}`;
    else if (ch === "\n") out += "\\n";
    else if (ch === "\t") out += "\\t";
    else if (ch >= " " && ch <= "~") out += ch;
    else for (let i = 0; i < ch.length; i++) out += `\\u${ch.charCodeAt(i).toString(16).padStart(4, "0")}`;
  }
  return `${out}\\n$`;
}

/** A single-quoted YAML scalar: backslashes stay literal, only `'` is doubled. */
export function yamlSingleQuoted(text) {
  if (/[\n\r]/.test(text)) throw new RegenError("a single-quoted YAML scalar must stay on one line here");
  return `'${text.replaceAll("'", "''")}'`;
}

export function graderSlug(file) {
  return file
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

export function wholeFileGrader(file, content) {
  return [
    "---",
    "# Generated by evals/fixtures/regen.mjs from scaffold.sh: the file must be byte-identical to what the scaffold wrote.",
    "type: regex",
    `pattern: ${yamlSingleQuoted(wholeFilePattern(content))}`,
    "target:",
    "  source: file",
    `  path: ${file}`,
    "---",
    "",
  ].join("\n");
}

// ---------------------------------------------------------------- heredocs

const HEREDOC = /<<-?\s*(?:'([A-Za-z_]\w*)'|"([A-Za-z_]\w*)"|\\?([A-Za-z_]\w*))/g;

/** Every heredoc delimiter used anywhere in a script. */
export function heredocDelimiters(script) {
  const found = new Set();
  for (const m of script.matchAll(HEREDOC)) found.add(m[1] ?? m[2] ?? m[3]);
  return found;
}

/** Locates the heredoc that `start` opens: the line must occur exactly once and quote its delimiter. */
export function findHeredoc(script, start) {
  if (/>>/.test(start)) throw new RegenError(`refusing an appending heredoc: ${start}`);
  const m = /<<-?'([A-Za-z_]\w*)'$/.exec(start);
  if (m === null) throw new RegenError(`heredoc start must end with a quoted delimiter: ${start}`);
  const delimiter = m[1];
  const lines = script.split("\n");
  const hits = lines.flatMap((line, i) => (line === start ? [i] : []));
  if (hits.length !== 1) throw new RegenError(`heredoc start found ${hits.length} times, expected once: ${start}`);
  const first = hits[0] + 1;
  const end = lines.indexOf(delimiter, first);
  if (end < 0) throw new RegenError(`heredoc has no closing ${delimiter}: ${start}`);
  return { lines, first, end, delimiter };
}

export function readHeredoc(script, start) {
  const { lines, first, end } = findHeredoc(script, start);
  return lines
    .slice(first, end)
    .map((l) => `${l}\n`)
    .join("");
}

export function replaceHeredoc(script, start, content) {
  if (!content.endsWith("\n")) throw new RegenError(`content for ${start} does not end with a newline`);
  const delimiters = heredocDelimiters(script);
  const body = content.slice(0, -1).split("\n");
  const clash = body.find((l) => delimiters.has(l));
  if (clash !== undefined) throw new RegenError(`content for ${start} contains a line equal to a heredoc delimiter: ${clash}`);
  const { lines, first, end } = findHeredoc(script, start);
  return [...lines.slice(0, first), ...body, ...lines.slice(end)].join("\n");
}

/** The file a `cat > <file> <<'X'` line writes, or null for `cat <<'X'` (stdout). */
function heredocTarget(start) {
  return /^cat\s+>\s*(\S+)\s+<</.exec(start)?.[1] ?? null;
}

// ---------------------------------------------------------------- pins

/** Every `owner/repo@<40-hex sha> # v<version>` in a text, in order. */
export function extractPins(text) {
  return [...text.matchAll(/([\w.-]+\/[\w.-]+)@([0-9a-f]{40}) # (v\d[\w.-]*)/g)].map((m) => ({
    action: m[1],
    sha: m[2],
    version: m[3],
    text: m[0],
  }));
}

/** The pinned commit of the newest pharn-ci version the manifest names: the one the install skill writes. */
export function latestPin(manifest) {
  const pin = manifest.pharnCi?.[manifest.latest];
  if (pin === undefined) throw new RegenError(`manifest.latest ${manifest.latest} is not a key of manifest.pharnCi`);
  return pin;
}

/**
 * Problems with the install skill's pins: pharn-ci itself must be the latest pinned commit with its ref as the
 * comment, and every other pin must appear, byte for byte, in pharn-ci's README or example workflows at that commit.
 */
export function pinProblems(reference, sources, manifest) {
  const latest = latestPin(manifest);
  const problems = [];
  const pins = extractPins(reference);
  if (pins.length === 0) problems.push("the pin reference lists no pins");
  for (const pin of pins) {
    if (pin.action === "pharn-dev/pharn-ci") {
      if (pin.sha !== latest.sha || pin.version !== latest.ref) {
        problems.push(`${pin.text} is not pharn-dev/pharn-ci@${latest.sha} # ${latest.ref}`);
      }
    } else if (!sources.some((s) => s.includes(pin.text))) {
      problems.push(`${pin.text} appears nowhere in pharn-ci's README or examples/workflows at ${latest.sha}`);
    }
  }
  return problems;
}

function pharnCiPinSources(pharnCi) {
  const examples = path.join(pharnCi, "examples/workflows");
  return [
    readFileSync(path.join(pharnCi, "README.md"), "utf8"),
    ...readdirSync(examples)
      .filter((f) => f.endsWith(".yml"))
      .map((f) => readFileSync(path.join(examples, f), "utf8")),
  ];
}

// ---------------------------------------------------------------- running

function childEnv() {
  // A small, fixed environment: no GITHUB_*, CI or NODE_* variables that could change what
  // pharn-ci or the test runner print, and no user or system git config.
  const env = {
    PATH: process.env.PATH ?? "",
    HOME: process.env.HOME ?? "",
    LC_ALL: "C",
    GIT_CONFIG_GLOBAL: "/dev/null",
    GIT_CONFIG_NOSYSTEM: "1",
  };
  if (process.env.TMPDIR !== undefined) env.TMPDIR = process.env.TMPDIR;
  return env;
}

function run(argv, cwd, { exits = [0] } = {}) {
  const r = spawnSync(argv[0], argv.slice(1), { cwd, env: childEnv(), encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
  if (r.error !== undefined) throw new RegenError(`${argv.join(" ")}: ${r.error.message}`);
  if (!exits.includes(r.status)) {
    throw new RegenError(`${argv.join(" ")} exited ${r.status ?? r.signal} in ${cwd}\n${r.stderr.trim()}`);
  }
  return r.stdout;
}

function getIn(obj, at) {
  return at.reduce((o, k) => (o === null || typeof o !== "object" ? undefined : o[k]), obj);
}

function setIn(obj, at, value) {
  const parent = getIn(obj, at.slice(0, -1));
  if (parent === null || typeof parent !== "object") throw new RegenError(`no ${at.join(".")} to set`);
  parent[at[at.length - 1]] = value;
}

function readInput(name) {
  if (name.includes("/") || !name.endsWith(".json")) throw new RegenError(`input must be a .json file in fixtures/inputs: ${name}`);
  return JSON.parse(readFileSync(path.join(FIXTURES, "inputs", name), "utf8"));
}

function json(value, indent) {
  return `${JSON.stringify(value, null, indent)}\n`;
}

function checkExpect(name, expect, reports) {
  const report = reports.get(expect.file) ?? (existsSync(path.join(FIXTURES, "inputs", expect.file)) ? readInput(expect.file) : undefined);
  if (report === undefined) throw new RegenError(`${name}: expect.file ${expect.file} is neither an artifact nor an input`);
  const facts = { verdict: report.verdict, codes: report.messages.map((m) => m.code) };
  if ("diffCoverage" in expect) facts.diffCoverage = report.diffCoverage;
  const dc = report.diffCoverage;
  for (const key of ["percent", "threshold", "coveredLines", "coverableLines"]) if (key in expect) facts[key] = dc?.[key];
  if ("uncoveredLines" in expect) facts.uncoveredLines = Object.fromEntries((dc?.files ?? []).map((f) => [f.path, f.uncoveredLines]));
  if ("schemaVersion" in expect) facts.schemaVersion = report.schemaVersion;
  if ("levels" in expect) facts.levels = report.messages.map((m) => m.level);
  const ti = report.testIntegrity;
  if ("testIntegrityMode" in expect) facts.testIntegrityMode = ti?.mode;
  if ("signals" in expect) facts.signals = (ti?.signals ?? []).map((s) => [s.id, s.severity, s.path, s.line]);
  if ("accepted" in expect) facts.accepted = ti?.accepted ?? null;
  const wanted = Object.fromEntries(Object.entries(expect).filter(([k]) => k !== "file"));
  const got = Object.fromEntries(Object.keys(wanted).map((k) => [k, facts[k]]));
  if (JSON.stringify(got) !== JSON.stringify(wanted)) {
    throw new RegenError(
      `${name}: ${expect.file} no longer has the facts the graders rely on\n  expected ${JSON.stringify(wanted)}\n  got      ${JSON.stringify(got)}`
    );
  }
}

/** Runs one case's scaffold in a temp dir and returns { scaffold, graders } as they should be on disk. */
function regenCase(name, spec, tools) {
  const caseDir = path.join(EVALS, name);
  const scaffoldPath = path.join(caseDir, "scaffold.sh");
  let scaffold = readFileSync(scaffoldPath, "utf8");
  const tmp = mkdtempSync(path.join(tmpdir(), "pharn-ci-regen-"));
  const tmpPaths = [...new Set([tmp, realpathSync(tmp)])];
  try {
    run(["bash", scaffoldPath], tmp);
    const graders = new Map();
    for (const file of spec.wholeFileGraders) {
      const full = path.join(tmp, file);
      if (!existsSync(full)) continue;
      graders.set(`unchanged-${graderSlug(file)}.md`, wholeFileGrader(file, readFileSync(full, "utf8")));
    }
    if (spec.testCommand !== null) run(spec.testCommand.argv, path.join(tmp, spec.testCommand.cwd));

    const reports = new Map();
    for (const artifact of spec.artifacts) {
      if (artifact.generated === false) {
        findHeredoc(scaffold, artifact.start);
        continue;
      }
      const src = artifact.source;
      let content;
      if (src.cli !== undefined) {
        const stdout = run(["node", tools.cli, ...src.cli], tmp, { exits: src.exits });
        if (src.cli.includes("json")) {
          let report = JSON.parse(stdout);
          if (artifact.appendMessage !== undefined) report.messages.push(readInput(artifact.appendMessage));
          if (artifact.acceptLabel !== undefined) report = applyAcceptLabel(name, report, artifact.acceptLabel, tools);
          // A kept report is not written into the scaffold: a later artifact renders it (a PR comment).
          if (artifact.keep !== undefined) {
            reports.set(artifact.keep, report);
            continue;
          }
          reports.set(heredocTarget(artifact.start), report);
          content = json(report, artifact.indent);
        } else {
          content = stdout;
        }
      } else if (src.file !== undefined) {
        content = readFileSync(path.join(tmp, src.file), "utf8");
      } else if (src.input !== undefined) {
        const value = readInput(src.input);
        const r = src.render;
        if (r !== undefined) {
          if (getIn(value, r.at) !== r.placeholder)
            throw new RegenError(`${name}: ${src.input} has no ${r.placeholder} at ${r.at.join(".")}`);
          const rendered = typeof r.report === "string" ? readInput(r.report) : reports.get(r.report.artifact);
          if (rendered === undefined) throw new RegenError(`${name}: no kept report ${JSON.stringify(r.report)} to render`);
          setIn(value, r.at, r.prefix + tools.renderMarkdown(rendered));
        }
        content = json(value, artifact.indent);
      } else {
        throw new RegenError(`${name}: artifact ${artifact.start} has no source`);
      }
      const leak = tmpPaths.find((p) => content.includes(p));
      if (leak !== undefined) throw new RegenError(`${name}: output for ${artifact.start} contains the temp path ${leak}`);
      scaffold = replaceHeredoc(scaffold, artifact.start, content);
    }
    if (spec.expect !== undefined) checkExpect(name, spec.expect, reports);
    if (spec.helperParity !== undefined) checkHelperParity(name, spec.helperParity, tmp, tools);
    return { scaffold, graders };
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

/**
 * The accept label as the pharn-ci Action applies it (packages/action/src/accept-label.ts), with pharn-ci core's own
 * functions, on the pull request, labels and issue events of a gh fixture: only in mode block with a block finding, and
 * only when the PR carries the label. The CLI never reads the label, so a case that shows an Action report with
 * TEST_INTEGRITY_ACCEPTED or TEST_INTEGRITY_ACCEPT_IGNORED gets it here, from the same events the stub gh replays.
 */
function applyAcceptLabel(name, report, spec, tools) {
  const { withAcceptLabel, carriesAcceptLabel, decideAcceptLabel, ignoreAcceptLabel, acceptTestIntegrity } = tools.core;
  if (typeof decideAcceptLabel !== "function") throw new RegenError(`${name}: this pharn-ci has no accept label`);
  const fixture = readInput(spec.fixture);
  const label = spec.label ?? "pharn/accepted";
  const labelled = withAcceptLabel(report, label);
  const { mode, signals } = labelled.testIntegrity;
  if (mode !== "block" || !signals.some((s) => s.severity === "block"))
    throw new RegenError(`${name}: the accept label is only read in mode block with a block finding`);
  if (carriesAcceptLabel(fixture.pr.labels, label) !== true)
    throw new RegenError(`${name}: ${spec.fixture} pr.labels does not carry ${label}`);
  const decision = decideAcceptLabel({ label, authorLogin: fixture.pr.author.login, events: fixture.events });
  return decision.honoured
    ? acceptTestIntegrity(labelled, { label, by: decision.by })
    : ignoreAcceptLabel(labelled, label, decision.reason);
}

const COVERAGE_CODES = new Set([
  "COVERAGE_FILE_MISSING",
  "COVERAGE_FILE_EMPTY",
  "COVERAGE_FORMAT_UNSUPPORTED",
  "COVERAGE_PATHS_UNMATCHED",
  "COVERAGE_PATHS_PARTIALLY_UNMATCHED",
  "COVERAGE_LINES_SKIPPED",
  "COVERAGE_FILE_TRACKED",
]);

/**
 * The install helper must agree with the pinned CLI on the case's coverage: the same coverage codes and the
 * same suggested root, then, with that root applied, the same again.
 */
function checkHelperParity(name, parity, tmp, tools) {
  const compare = (root) => {
    const args = parity.coverage.flatMap((c) => ["--coverage", c]);
    const rootArgs = root === null ? [] : ["--coverage-root", root];
    const helper = JSON.parse(run(["node", HELPER, ...args, ...rootArgs], tmp));
    const report = JSON.parse(
      run(["node", tools.cli, "check", "--base", "HEAD", "--format", "json", ...args, ...rootArgs], tmp, { exits: [0, 1] })
    );
    const cliCodes = report.messages.map((m) => m.code).filter((c) => COVERAGE_CODES.has(c));
    const unmatched = report.messages.find((m) => m.code === "COVERAGE_PATHS_UNMATCHED");
    const cliRoot = unmatched === undefined ? null : (/look relative to `([^`]+)`/.exec(unmatched.text)?.[1] ?? null);
    const got = { codes: helper.codes, suggestedRoot: helper.paths?.suggestedRoot ?? null };
    const wanted = { codes: cliCodes, suggestedRoot: cliRoot };
    if (JSON.stringify(got) !== JSON.stringify(wanted)) {
      const label = root === null ? "" : ` with --coverage-root ${root}`;
      throw new RegenError(
        `${name}: check-coverage.mjs disagrees with pharn-ci${label}\n  pharn-ci ${JSON.stringify(wanted)}\n  helper   ${JSON.stringify(got)}`
      );
    }
    return cliRoot;
  };
  const suggested = compare(null);
  if (suggested !== null) compare(suggested);
}

function lineDiff(label, before, after) {
  const a = before.split("\n");
  const b = after.split("\n");
  let head = 0;
  while (head < a.length && head < b.length && a[head] === b[head]) head++;
  let tail = 0;
  while (tail < a.length - head && tail < b.length - head && a[a.length - 1 - tail] === b[b.length - 1 - tail]) tail++;
  const out = [`--- ${label}`, `+++ ${label} (regenerated)`, `@@ line ${head + 1} @@`];
  for (const l of a.slice(head, a.length - tail)) out.push(`-${l}`);
  for (const l of b.slice(head, b.length - tail)) out.push(`+${l}`);
  return out.join("\n");
}

async function loadTools(pharnCi, version, pin) {
  const head = run(["git", "-C", pharnCi, "rev-parse", "HEAD"], process.cwd()).trim();
  if (head !== pin.sha) throw new RegenError(`${pharnCi} (pharn-ci ${version}) is at ${head}, expected ${pin.sha}`);
  const cli = path.join(pharnCi, "packages/cli/dist/index.js");
  const core = path.join(pharnCi, "packages/core/dist/index.js");
  for (const f of [cli, core]) {
    if (!existsSync(f))
      throw new RegenError(`${f} is missing: run pnpm install --frozen-lockfile && pnpm --filter @pharn-ci/cli... build in ${pharnCi}`);
  }
  const cliVersion = run(["node", cli, "--version"], pharnCi).trim();
  if (cliVersion !== pin.cliVersion) throw new RegenError(`pharn-ci ${version}: the CLI prints ${cliVersion}, expected ${pin.cliVersion}`);
  const coreModule = await import(pathToFileURL(core).href);
  return { dir: pharnCi, cli, renderMarkdown: coreModule.renderMarkdown, core: coreModule };
}

/** The `<version>=<dir>` value of a --pharn-ci argument. */
export function parsePharnCiArg(value) {
  const m = /^([^=]+)=(.+)$/.exec(value ?? "");
  if (m === null) throw new RegenError(`--pharn-ci takes <version>=<pharn-ci checkout>, got ${value}`);
  return { version: m[1], dir: m[2] };
}

export function parseArgs(argv) {
  const opts = { mode: undefined, pharnCi: new Map() };
  const addPharnCi = (value) => {
    const { version, dir } = parsePharnCiArg(value);
    if (opts.pharnCi.has(version)) throw new RegenError(`--pharn-ci ${version} given twice`);
    opts.pharnCi.set(version, path.resolve(dir));
  };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--check" || a === "--write") {
      if (opts.mode !== undefined && opts.mode !== a.slice(2)) throw new RegenError("pass --check or --write, not both");
      opts.mode = a.slice(2);
    } else if (a === "--pharn-ci") addPharnCi(argv[++i]);
    else if (a.startsWith("--pharn-ci=")) addPharnCi(a.slice("--pharn-ci=".length));
    else throw new RegenError(`unknown argument: ${a}`);
  }
  if (opts.mode === undefined || opts.pharnCi.size === 0) {
    throw new RegenError("usage: regen.mjs --check|--write --pharn-ci <version>=<pharn-ci checkout> [--pharn-ci <version>=<checkout>]...");
  }
  return opts;
}

/** Every version in manifest.pharnCi must be given a checkout, and nothing else may be. */
export function checkoutProblems(manifest, given) {
  const pinned = Object.keys(manifest.pharnCi ?? {});
  const problems = [];
  for (const v of pinned) if (!given.has(v)) problems.push(`no --pharn-ci ${v}=<checkout> (pinned at ${manifest.pharnCi[v].sha})`);
  for (const v of given.keys())
    if (!pinned.includes(v)) problems.push(`--pharn-ci ${v} is not a version in manifest.pharnCi (${pinned.join(", ")})`);
  const names = Object.keys(manifest.cases ?? {});
  for (const [name, spec] of Object.entries(manifest.cases ?? {})) {
    // A case with a byte-identical scaffold and spec reuses that case's regenerated files instead of a second run.
    if (spec.sameAs !== undefined) {
      const source = manifest.cases[spec.sameAs];
      if (source === undefined || source.sameAs !== undefined || names.indexOf(spec.sameAs) > names.indexOf(name)) {
        problems.push(`case ${name}: sameAs ${spec.sameAs} must name an earlier case that is not itself sameAs`);
      } else if (Object.keys(spec).length !== 1) {
        problems.push(`case ${name}: a sameAs case takes no other settings`);
      }
      continue;
    }
    if (!pinned.includes(spec.pharnCi)) problems.push(`case ${name} names pharn-ci ${spec.pharnCi}, which manifest.pharnCi does not pin`);
  }
  if (!pinned.includes(manifest.latest)) problems.push(`manifest.latest ${manifest.latest} is not a key of manifest.pharnCi`);
  return problems;
}

export async function main(argv) {
  const { mode, pharnCi } = parseArgs(argv);
  const manifest = JSON.parse(readFileSync(path.join(FIXTURES, "manifest.json"), "utf8"));
  if (process.version !== manifest.node) throw new RegenError(`run this with Node ${manifest.node} (this is ${process.version})`);
  const problems = checkoutProblems(manifest, pharnCi);
  if (problems.length > 0) throw new RegenError(problems.join("\n"));
  const tools = new Map();
  for (const [version, dir] of pharnCi) tools.set(version, await loadTools(dir, version, manifest.pharnCi[version]));
  const diffs = [];
  const latestDir = tools.get(manifest.latest).dir;
  for (const problem of pinProblems(readFileSync(PIN_REFERENCE, "utf8"), pharnCiPinSources(latestDir), manifest))
    diffs.push(`pin: ${problem}`);
  if (diffs.length === 0) console.error("pins: ok");
  const results = new Map();
  for (const [name, spec] of Object.entries(manifest.cases)) {
    // CI checks that a sameAs case's scaffold is byte-identical to its source's, so the output is too.
    const result = spec.sameAs !== undefined ? results.get(spec.sameAs) : regenCase(name, spec, tools.get(spec.pharnCi));
    results.set(name, result);
    const { scaffold, graders } = result;
    const want = new Map([["scaffold.sh", scaffold], ...[...graders].map(([f, c]) => [`graders/${f}`, c])]);
    const graderDir = path.join(EVALS, name, "graders");
    const stale = readdirSync(graderDir).filter((f) => /^unchanged-.*\.md$/.test(f) && !graders.has(f));
    for (const [rel, content] of want) {
      const file = path.join(EVALS, name, rel);
      const current = existsSync(file) ? readFileSync(file, "utf8") : null;
      if (current === content) continue;
      if (mode === "write") writeFileSync(file, content);
      else diffs.push(current === null ? `missing ${name}/${rel}` : lineDiff(`${name}/${rel}`, current, content));
    }
    for (const f of stale) {
      if (mode === "write") unlinkSync(path.join(graderDir, f));
      else diffs.push(`stale ${name}/graders/${f}`);
    }
    console.error(`${name}: ok`);
  }
  if (diffs.length > 0) {
    console.log(diffs.join("\n\n"));
    console.error("\nEval fixtures are out of date: run regen.mjs --write and commit the result.");
    return 1;
  }
  console.error(mode === "write" ? "Eval fixtures written." : "Eval fixtures are up to date.");
  return 0;
}

let isMain;
try {
  isMain = process.argv[1] !== undefined && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url);
} catch {
  isMain = false;
}
if (isMain) {
  main(process.argv.slice(2)).then(
    (code) => {
      process.exitCode = code;
    },
    (err) => {
      if (!(err instanceof RegenError)) throw err;
      console.error(`regen: ${err.message}`);
      process.exitCode = 2;
    }
  );
}
